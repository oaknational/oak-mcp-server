import { readFileSync, writeFileSync } from 'node:fs';
import { relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseArgs } from 'node:util';
import {
  captureInMemory,
  diffSurfaces,
  formatReport,
  judgeDifferences,
  parseBaseline,
  renderSurfaceFile,
  type SurfaceSnapshot,
} from './surface-diff.ts';

const SNAPSHOT_PATH = fileURLToPath(
  new URL('../../apps/server/served-surface.json', import.meta.url),
);
const SOURCE = 'generated by pnpm surface:snapshot from the in-memory server; do not edit by hand';

export function renderSnapshot(snapshot: SurfaceSnapshot, path = SNAPSHOT_PATH): Promise<string> {
  return renderSurfaceFile(snapshot, SOURCE, path);
}

export async function checkSnapshot(
  committed: string | undefined,
  current: SurfaceSnapshot,
  path = SNAPSHOT_PATH,
): Promise<string | undefined> {
  const shown = relative(process.cwd(), path);
  if (committed === undefined) {
    return `${shown} is missing. Run pnpm surface:snapshot and commit it.\n`;
  }
  if (committed === (await renderSnapshot(current, path))) {
    return undefined;
  }
  const report = judgeDifferences(diffSurfaces(parseBaseline(committed), current), []);
  const detail =
    report.unexpected.length === 0
      ? 'its layout differs from the generated file\n'
      : formatReport(report);
  return `${shown} is stale: ${detail}Run pnpm surface:snapshot and commit the result.\n`;
}

function readCommitted(): string | undefined {
  try {
    return readFileSync(SNAPSHOT_PATH, 'utf8');
  } catch {
    return undefined;
  }
}

async function main(argv: readonly string[]): Promise<number> {
  const { values } = parseArgs({
    args: [...argv],
    options: { check: { type: 'boolean', default: false } },
    strict: true,
  });
  const current = await captureInMemory();
  const shown = relative(process.cwd(), SNAPSHOT_PATH);
  if (!values.check) {
    writeFileSync(SNAPSHOT_PATH, await renderSnapshot(current));
    process.stdout.write(`wrote ${shown}\n`);
    return 0;
  }
  const problem = await checkSnapshot(readCommitted(), current);
  if (problem !== undefined) {
    process.stderr.write(problem);
    return 1;
  }
  process.stdout.write(`${shown} matches the served surface\n`);
  return 0;
}

if (import.meta.main) {
  try {
    process.exitCode = await main(process.argv.slice(2));
  } catch (error) {
    process.stderr.write(
      `surface-snapshot: ${error instanceof Error ? error.message : String(error)}\n`,
    );
    process.exitCode = 2;
  }
}
